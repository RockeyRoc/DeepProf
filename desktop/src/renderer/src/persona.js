/* ──────────────────────────────────────────────────────────
 * 台词库。每个场景是数组，会在场景切换时随机挑一条。
 * 挑的时机很重要：不能在 render 里随机 —— 那样每帧重渲染都会换一句。
 * ────────────────────────────────────────────────────────── */

export const LINES = {
  /** 首次见面 / 没聊过天时的默认气泡 */
  greet: [
    '来了。今天想从哪儿开始？',
    '书打开了，你说吧。',
    '有题就问，别客气。'
  ],

  /** 模型在加载 / 思考 */
  loading: [
    '唔…我想想。',
    '等一下，我理一下思路。',
    '让我看看这个。'
  ],

  /** 出错。不是「出错了，可以重试」那种报错信息，是人在说话 */
  error: [
    '啧，掉线了。要我再试一次吗？',
    '刚才断了。再试一次？',
    '没连上。你等我一下，我再试。'
  ],

  /** 用户主动取消 */
  cancelled: [
    '行，那先停这儿。',
    '好，不讲了。想继续随时说。',
    '打断得挺及时。'
  ],

  /** 断线重连中 */
  reconnecting: [
    '信号有点差…我重连一下。',
    '等我，在重连。',
    '网又抽了，稍等。'
  ],

  /** 精力见底睡着了 */
  asleep: ['Zzz…', '（睡着了）', '……呼。'],

  /**
   * 点了身体（不是摸头）。
   *
   * ⚠️ 这一组是**必须的**，不能省。原来点身体时没有台词，气泡会回落到
   *    「最后一条回复」—— 表现就是"我根本没问它，它又把上一题答了一遍"。
   *    点了就该有个当场反应，而不是翻旧账。
   */
  tap: ['嗯？', '怎么了？', '有事说事。', '在呢。'],

  /**
   * 摸头。**按好感度阶段换语气** —— 这是好感度系统唯一被用户直接感知到的地方。
   * 刻意不写撒娇台词，越亲近变化越像"熟人"，而不是"更黏人"。
   */
  pat: {
    stranger: ['诶？', '干嘛。', '别闹，看题。'],
    familiar: ['嗯…行了行了。', '手拿开，看题。', '（躲了一下）'],
    close: ['……就这一次。', '题做完了吗就摸头。', '（没躲）'],
    attached: ['来了啊。', '……先坐下，我给你留了道题。', '（抬头看了一眼，又低下去）']
  }
}

/** 按场景随机挑一句 */
export function pickLine(scene) {
  const pool = LINES[scene]
  if (!Array.isArray(pool) || !pool.length) return ''
  return pool[Math.floor(Math.random() * pool.length)]
}

/** 摸头台词，按好感度阶段挑 */
export function pickPatLine(stageKey) {
  const pool = LINES.pat[stageKey] || LINES.pat.stranger
  return pool[Math.floor(Math.random() * pool.length)]
}

/** 运行状态 → 台词场景 */
export const STATUS_TO_SCENE = {
  loading: 'loading',
  error: 'error',
  cancelled: 'cancelled',
  reconnecting: 'reconnecting'
}

